export function searchFormulary(query) {
  if (!query || query.length < 2) return Object.values(FORMULARY);
  const q = query.toLowerCase();
  return Object.values(FORMULARY).filter(d =>
    d.generic?.toLowerCase().includes(q) ||
    d.class?.toLowerCase().includes(q) ||
    d.indications?.toLowerCase().includes(q) ||
    d.formulations?.some(f =>
      f.brands?.toLowerCase().includes(q) ||
      f.form?.toLowerCase().includes(q)
    )
  );
}

export function getFormularyDrug(name) {
  if (!name) return null;
  const key = name.toLowerCase().replace(/\s+/g, "").replace(/[^a-z]/g, "");
  return FORMULARY[key] || Object.values(FORMULARY).find(d =>
    d.generic?.toLowerCase().replace(/\s+/g, "") === key
  ) || null;
}